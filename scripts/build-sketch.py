#!/usr/bin/env python3
"""Write catalogue model modules from scene definitions and the shared engine."""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL_SOURCES = ROOT / 'model-source/sketch'
PRODUCTS = json.loads((ROOT / 'content/products.json').read_text())
ENGINE_HASH = hashlib.sha256((ROOT / 'engine.js').read_bytes()).hexdigest()[:12]


def read_scene(product_id):
    source = MODEL_SOURCES / f'{product_id}.js'
    if source.exists():
        # New scene modules export one factory, which uses the engine's S and M.
        text = source.read_text()
        declaration = re.search(r'^export\s+const\s+makeScene\s*=\s*', text, re.M)
        if not declaration:
            raise ValueError(f'{source} must export a makeScene factory')
        return text[declaration.end():].strip().removesuffix(';'), {}

    # The reference HTMLs are kept for comparison with the reviewed original scenes.
    html = (MODEL_SOURCES / f'{product_id}.html').read_text()
    scripts = re.findall(r'<script[^>]*>([\s\S]*?)</script>', html)
    entry = "Sketch3D.mount('#app', "
    script = next(script for script in scripts if '\n' + entry in script)
    call = script.split('\n' + entry, 1)[1].strip()
    if not call.endswith(');'):
        raise ValueError(f'Unexpected scene factory in {product_id}')
    offsets = re.search(r'const explodeVectors=(\{[^;]+\});', html)

    options = {'explodeOffsets': json.loads(offsets[1])} if offsets else {}
    if product_id == 'care-bed':
        options.update(
            auditGeometry=True,
            qualifyNotes=True,
            ink={
                'edgeTiming': 'vertex',
                'inkExtension': 40,
                'inkBowMin': 24,
                'inkBowFactor': 0.04,
                'glowBlend': 'darken',
            },
        )
    return call[:-2], options


for figure, product in enumerate(PRODUCTS, 1):
    product_id = product['id']
    scene, options = read_scene(product_id)
    model_options = json.dumps({'id': product_id, 'figure': figure, **options},
                               ensure_ascii=False, separators=(',', ':'))
    module = (
        '// Generated by scripts/build-sketch.py from the corresponding model source.\n'
        f'import {{ defineModel }} from "../engine.js?v={ENGINE_HASH}";\n\n'
        f'export const makeScene = {scene};\n\n'
        f'export const {{ createScene, mount }} = defineModel(makeScene, {model_options});\n'
    )
    (ROOT / 'models' / f'{product_id}.js').write_text(module)

print(f'Built {len(PRODUCTS)} scene modules using the shared engine.')
